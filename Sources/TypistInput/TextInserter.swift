import AppKit
import ApplicationServices

public enum InsertionMethod: String, CaseIterable, Sendable, Codable {
    /// Put the text on the clipboard, press ⌘V, then restore the clipboard.
    case pasteboard
    /// Replace the focused element's selection through the Accessibility API.
    case accessibility
    /// Post synthetic key events carrying the text.
    case typing
}

public struct InsertionReport: Sendable, Codable {
    public var method: InsertionMethod
    /// The API calls went through. It does not prove that the app accepted the text.
    public var apiSucceeded: Bool
    public var error: String?
    public var milliseconds: Double
    /// Pasteboard method only: the clipboard was restored to exactly what it held before.
    public var clipboardRestored: Bool?
    public var details: String?
}

/// Inserts text into the app that has keyboard focus. Needs the Accessibility permission.
@MainActor
public enum TextInserter {
    public static func insert(
        _ text: String, method: InsertionMethod, restoreDelay: Duration = .milliseconds(250), typingChunk: Int = 16,
        restoreClipboard: Bool = true
    ) async -> InsertionReport {
        let start = Date()
        var report: InsertionReport
        switch method {
        case .pasteboard:
            report = await paste(text, restoreDelay: restoreDelay, restoreClipboard: restoreClipboard)
        case .accessibility:
            report = setSelectedText(text)
        case .typing:
            report = await type(text, chunk: typingChunk)
        }
        report.milliseconds = Date().timeIntervalSince(start) * 1000
        return report
    }

    // MARK: - Pasteboard

    /// Types that tell clipboard managers not to record this content
    /// (http://nspasteboard.org).
    static let transientTypes: [NSPasteboard.PasteboardType] = [
        .init("org.nspasteboard.TransientType"), .init("org.nspasteboard.AutoGeneratedType"),
    ]

    private static func paste(_ text: String, restoreDelay: Duration, restoreClipboard: Bool) async -> InsertionReport {
        let pasteboard = NSPasteboard.general
        let snapshot = PasteboardSnapshot(pasteboard)

        let item = NSPasteboardItem()
        item.setString(text, forType: .string)
        for type in transientTypes { item.setData(Data(), forType: type) }
        pasteboard.clearContents()
        pasteboard.writeObjects([item])
        let ourChange = pasteboard.changeCount

        let pasteKey = KeyboardLayout.keyCode(forShortcut: "v") ?? Keys.v
        postKey(pasteKey, flags: .maskCommand)
        try? await Task.sleep(for: restoreDelay)

        var report = InsertionReport(
            method: .pasteboard, apiSucceeded: true, milliseconds: 0,
            details: "⌘V on key \(pasteKey) in \(KeyboardLayout.currentLayoutID ?? "unknown layout")")
        if !restoreClipboard {
            report.clipboardRestored = false
            report.details = (report.details ?? "") + "; clipboard keeps the dictated text"
        } else if pasteboard.changeCount == ourChange {
            snapshot.restore(to: pasteboard)
            report.clipboardRestored = snapshot.matches(pasteboard)
        } else {
            report.clipboardRestored = false
            report.details = (report.details ?? "") + "; clipboard changed by another app before restoring, left as is"
        }
        return report
    }

    // MARK: - Accessibility

    private static func setSelectedText(_ text: String) -> InsertionReport {
        guard let element = FocusInspector.focusedElement() else {
            return InsertionReport(
                method: .accessibility, apiSucceeded: false, error: "no focused element", milliseconds: 0)
        }
        let result = AXUIElementSetAttributeValue(element, kAXSelectedTextAttribute as CFString, text as CFString)
        return InsertionReport(
            method: .accessibility, apiSucceeded: result == .success,
            error: result == .success ? nil : "AXError \(result.rawValue)", milliseconds: 0)
    }

    // MARK: - Typing

    /// How synthetic typing events are created and delivered. The spike compares them.
    public enum TypingVariant: String, Sendable, Codable, CaseIterable {
        case hid, session, pid, privateSource
    }

    public static var typingVariant: TypingVariant = .hid

    private static func type(_ text: String, chunk: Int) async -> InsertionReport {
        let source = CGEventSource(stateID: typingVariant == .privateSource ? .privateState : .combinedSessionState)
        var events = 0
        for (index, line) in text.split(separator: "\n", omittingEmptySubsequences: false).enumerated() {
            if index > 0 {
                postKey(Keys.returnKey)
                events += 1
            }
            // Never split a character (an emoji is two UTF-16 units) between events.
            var buffer: [UniChar] = []
            for character in line {
                let units = Array(String(character).utf16)
                if buffer.count + units.count > chunk, !buffer.isEmpty {
                    postUnicode(buffer, source: source)
                    events += 1
                    buffer = []
                    try? await Task.sleep(for: .milliseconds(2))
                }
                buffer += units
            }
            if !buffer.isEmpty {
                postUnicode(buffer, source: source)
                events += 1
            }
        }
        return InsertionReport(
            method: .typing, apiSucceeded: true, milliseconds: 0,
            details: "\(events) key events, chunk \(chunk), variant \(typingVariant.rawValue)")
    }

    private static func postUnicode(_ units: [UniChar], source: CGEventSource?) {
        var units = units
        let pid = NSWorkspace.shared.frontmostApplication?.processIdentifier
        for keyDown in [true, false] {
            guard let event = CGEvent(keyboardEventSource: source, virtualKey: 0, keyDown: keyDown) else { continue }
            event.keyboardSetUnicodeString(stringLength: units.count, unicodeString: &units)
            switch typingVariant {
            case .hid, .privateSource: event.post(tap: .cghidEventTap)
            case .session: event.post(tap: .cgSessionEventTap)
            case .pid: if let pid { event.postToPid(pid) }
            }
        }
    }

    // MARK: - Keys

    enum Keys {
        /// Virtual key codes are positions on an ANSI keyboard, not characters.
        static let v: CGKeyCode = 9
        static let s: CGKeyCode = 1
        static let returnKey: CGKeyCode = 36
    }

    /// Presses ⌘ and the key that produces `character` in the current layout.
    public static func postShortcut(_ character: Character) {
        guard let key = KeyboardLayout.keyCode(forShortcut: character) else { return }
        postKey(key, flags: .maskCommand)
    }

    public static func postSave() {
        postShortcut("s")
    }

    static func postKey(_ key: CGKeyCode, flags: CGEventFlags = []) {
        let source = CGEventSource(stateID: .combinedSessionState)
        for keyDown in [true, false] {
            let event = CGEvent(keyboardEventSource: source, virtualKey: key, keyDown: keyDown)
            event?.flags = flags
            event?.post(tap: .cghidEventTap)
        }
    }
}

/// A copy of everything on a pasteboard, every item in every type.
struct PasteboardSnapshot {
    private let items: [[(NSPasteboard.PasteboardType, Data)]]

    init(_ pasteboard: NSPasteboard) {
        items = (pasteboard.pasteboardItems ?? []).map { item in
            item.types.compactMap { type in item.data(forType: type).map { (type, $0) } }
        }
    }

    func restore(to pasteboard: NSPasteboard) {
        pasteboard.clearContents()
        guard !items.isEmpty else { return }
        let restored = items.map { entries in
            let item = NSPasteboardItem()
            for (type, data) in entries { item.setData(data, forType: type) }
            return item
        }
        pasteboard.writeObjects(restored)
    }

    func matches(_ pasteboard: NSPasteboard) -> Bool {
        let current = PasteboardSnapshot(pasteboard).items
        guard current.count == items.count else { return false }
        return zip(current, items).allSatisfy { lhs, rhs in
            Dictionary(lhs, uniquingKeysWith: { a, _ in a }) == Dictionary(rhs, uniquingKeysWith: { a, _ in a })
        }
    }
}
